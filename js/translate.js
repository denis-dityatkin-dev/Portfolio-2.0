function setLanguage(lang) {
	if (!translations[lang]) lang = 'en';

	const t = translations[lang];
	saveLanguage(lang);
	document.documentElement.lang = lang;

	// -------- Простые textContent --------
	Object.entries(TEXT_MAP).forEach(([sel, key]) => setText(sel, t[key]));

	// -------- Заголовки с # и / --------
	Object.entries(HASH_TITLES).forEach(([sel, key]) =>
		setHTML(sel, `<span>#</span>${t[key]}`)
	);
	Object.entries(SLASH_TITLES).forEach(([sel, key]) =>
		setHTML(sel, `<span>/</span>${t[key]}`)
	);

	// -------- Hero (со span внутри) --------
	setHTML('.main-section__title', `${t.heroTitle}<span>${t.heroDeveloper}</span>`);
	setHTML('.decor-main-section__subtitle', `${t.heroAvailable}<span>${t.heroFreelance}</span>`);

	// -------- About home: 3 абзаца --------
	const aboutKeys = ['aboutHello', 'aboutText1', 'aboutText2'];
	$$('.about__text p').forEach((p, i) => {
		if (aboutKeys[i]) p.textContent = t[aboutKeys[i]];
	});

	// -------- Проекты home --------
	PROJECTS_HOME.forEach((name, i) => {
		const n = i + 1;
		setText(`.projects__item:nth-child(${n}) .body-item-projects__link-title`, t[`${name}Title`]);
		setText(`.projects__item:nth-child(${n}) .body-item-projects__text p`, t[`${name}Text`]);
	});

	// -------- Проекты works --------
	PROJECTS_WORKS.forEach((name, i) => {
		const n = i + 1;
		setText(`.work .projects__item:nth-child(${n}) .body-item-projects__link-title`, t[`${name}WorkTitle`]);
		setText(`.work .projects__item:nth-child(${n}) .body-item-projects__text p`, t[`${name}WorkText`]);
	});

	// -------- Кнопки проектов (дома + works одним селектором) --------
	setTextAll('.projects__item .item-projects__button.button__live:first-child', t.liveDemo);
	setTextAll('.projects__item .item-projects__button.button__live:nth-child(2)', t.github);

	// -------- Skills home --------
	['frontend', 'tools', 'alsoTitle'].forEach((key, i) =>
		setText(`.item-skill__item:nth-child(${i + 1}) .item-skill__item-title`, t[key])
	);

	// -------- Skills about page --------
	['aboutPageFrontend', 'aboutPageTools', 'alsoTitle'].forEach((key, i) =>
		setText(`.skills-section .item-skill__section-item:nth-child(${i + 1}) .item-skill__item-title`, t[key])
	);

	// -------- Fun facts --------
	FACTS.forEach((key, i) =>
		setText(`.facts .content-fact__item:nth-child(${i + 1})`, t[key])
	);

	// -------- Pricing --------
	PRICING_ITEMS.forEach((item, i) => {
		const n = i + 1;
		const base = `.pricing__item:nth-child(${n})`;

		setText(`${base} .pricing__title`, t[item.title]);
		setText(`${base} .pricing__text p`, t[item.text]);

		const timeEl = $$('.pricing__time')[i];
		if (timeEl) {
			timeEl.innerHTML = `<span>${t.estimatedTime}</span>${t[item.time]}`;
		}

		item.prices.forEach(([sizeKey, priceKey], j) => {
			const m = j + 1;
			setText(`${base} .pricing__price-item:nth-child(${m}) span:nth-child(1)`, t[sizeKey]);
			setText(`${base} .pricing__price-item:nth-child(${m}) span:nth-child(2)`, t[priceKey]);
		});
	});

	// -------- What I do --------
	SERVICES.forEach(([titleKey, textKey], i) => {
		const item = $$('.services__item')[i];
		if (!item) return;
		const h3 = item.querySelector('h3');
		const p = item.querySelector('p');
		if (h3) h3.textContent = t[titleKey];
		if (p) p.textContent = t[textKey];
	});

	// -------- How I work --------
	PROCESS.forEach(([titleKey, textKey], i) => {
		const item = $$('.process__item')[i];
		if (!item) return;
		const h3 = item.querySelector('h3');
		const p = item.querySelector('p');
		if (h3) h3.textContent = t[titleKey];
		if (p) p.textContent = t[textKey];
	});

	// -------- Select --------
	const select = document.getElementById('lang-select');
	if (select) select.value = lang;
}

